"""**`There bin are createsd for the three numerical variable. For BMI it's BMI_BIn, for PhysHlth it is PhysHlth_Bin and for MentHlth it is MentHlth_Bin.`**

# **Feature Selection**

**`This segment consists of the code for feature selection. For feature selection, several methods will be utilized: Univariate Feature Selection, Recursive Feature Elimination, Random Forest Classifier, and XGBoost Classifier. For all the feature selection models, the top 10 selected features will be provided for use in the ML models.`**

**Univariate Feature Selection**

**`Univariate feature selection is a technique used to identify the most important features (columns) for machine learning model by evaluating each feature individually in relation to the target variable. This method examines each feature one at a time, rather than considering combinations of features, to determine how well each one predicts the outcome. It applies a statistical test to each feature and the target (for example, whether a person has diabetes: yes or no). The features that show the strongest relationship with the target variable are retained for the model.`**
"""

from sklearn.feature_selection import SelectKBest, f_classif

X = data.drop('Diabetes_binary', axis=1)
y = data['Diabetes_binary']

# Drop non-numeric columns and rows with NaNs
X_numeric = X.drop(columns=['BMI_Bin', 'MentHlth_Bin', 'PhysHlth_Bin'])
X_numeric = X_numeric.dropna()
y_cleaned = y[X_numeric.index] # Keep corresponding y values

selector = SelectKBest(score_func=f_classif, k=10)
X_new = selector.fit_transform(X_numeric, y_cleaned)

# Show selected feature names
selected_features = X_numeric.columns[selector.get_support()]
print("Top Features:", selected_features)

"""**`From the univariate feature selection the top 10 selected features are: 'HighBP', 'HighChol', 'BMI', 'GenHlth', 'DiffWalk', 'Age', 'Risk_Score','CardioRisk', 'StrokeRisk', 'PoorGeneralHealth'`**

**Recursive Feature Elimination**

**`Recursive Feature Elimination (RFE) is a wrapper-based method for feature selection that identifies the most important features by training a model repeatedly and step-by-step removing the least important features.`**
"""

from sklearn.feature_selection import RFE
from sklearn.linear_model import LogisticRegression

model = LogisticRegression(solver='liblinear')
rfe = RFE(model, n_features_to_select=10)

# Use the X_numeric DataFrame which excludes non-numeric columns
fit = rfe.fit(X_numeric, y_cleaned)

selected_columns = X_numeric.columns[fit.support_]
print("Selected Features:", selected_columns)

"""**`From the Recursive Feature Elimination method the top 10 selected features are 'HighBP', 'CholCheck', 'Smoker', 'PhysActivity', 'HvyAlcoholConsump','GenHlth','Risk_Score', 'HealthyDiet', 'RiskScore_DietActivity','CardioRisk'. `**

**Model-Based Selection (Embedded Method)**

`**Use feature importances from a tree-based model like Random Forest and Xgboost**`

**`Random Forest is an ensemble model based on decision trees that inherently calculates feature importance by evaluating the usefulness of each feature in splitting the data to enhance predictions. Each decision tree in the forest uses different features for these splits. One of the two main factors that determine the importance of each feature is the extent to which it reduces impurity (such as the Gini index) across all trees. Another is how frequently and effectively it is employed in decision-making.`**
"""

from sklearn.ensemble import RandomForestClassifier

# Drop non-numeric columns before fitting the model
X_numeric = X.drop(columns=['BMI_Bin', 'MentHlth_Bin', 'PhysHlth_Bin'])

rf = RandomForestClassifier()
rf.fit(X_numeric, y)

importances = rf.feature_importances_
top_features = X_numeric.columns[np.argsort(importances)[::-1][:10]]
print("Top features:", top_features)

"""**`The selected features from the random forest classifier are 'BMI', 'Age' 'Income', 'GenHlth', 'Education', 'PhysHlth','CardioRisk', 'HighBP', 'StrokeRisk', 'MentHlth'.`**

**`XGBoost performs feature selection as an embedded method by utilizing the feature importance derived from a trained model to rank and eliminate unimportant features. This approach is particularly effective for high-dimensional datasets, such as those used in health predictions.`**
"""

from xgboost import XGBClassifier

model = XGBClassifier(enable_categorical=True)
model.fit(X, y)

importances = model.feature_importances_
selected_columns = X.columns[importances > 0.01]  # Adjust threshold
print("Selected Features:", selected_columns)

"""**`THe top 10 selected feature from the XGBoost Classifier feature selection are:'HighBP', 'CholCheck', 'BMI', 'HvyAlcoholConsump', 'GenHlth','DiffWalk', 'Sex', 'Age', 'CardioRisk' `**"""